def match_card_template(
    emulator,
    chosen_card_index,
    threshold: float = HAND_TEMPLATE_THRESHOLD,
    return_score: bool = False,
) -> str | tuple[str | None, float] | None:
    templates = _load_card_templates()
    if not templates:
        return None
    crop = _get_card_crop(emulator, chosen_card_index)
    if crop is None:
        return None
    crop_gray = cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY)
    best_id = None
    best_score = -1.0
    for card_id, tmpl in templates:
        if ACTIVE_DECK_FILTER is not None and card_id not in ACTIVE_DECK_FILTER:
            continue
        tmpl_gray = cv2.cvtColor(tmpl, cv2.COLOR_BGR2GRAY)
        if tmpl_gray.shape != crop_gray.shape:
            tmpl_gray = cv2.resize(tmpl_gray, (crop_gray.shape[1], crop_gray.shape[0]))
        res = cv2.matchTemplate(crop_gray, tmpl_gray, cv2.TM_CCOEFF_NORMED)
        score = float(res[0][0])
        if score > best_score:
            best_score = score
            best_id = card_id
    if return_score:
        return best_id, best_score
    if best_id is not None and best_score >= threshold:
        return best_id
    return None


def get_hand_template_scores(emulator, topk: int = 3) -> dict[int, list[tuple[str, float]]]:
    templates = _load_card_templates()
    if not templates:
        return {}
    results: dict[int, list[tuple[str, float]]] = {}
    for idx in range(4):
        crop = _get_card_crop(emulator, idx)
        if crop is None or crop.size == 0:
            continue
        crop_gray = cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY)
        scores: dict[str, float] = {}
        for card_id, tmpl in templates:
            if ACTIVE_DECK_FILTER is not None and card_id not in ACTIVE_DECK_FILTER:
                continue
            tmpl_gray = cv2.cvtColor(tmpl, cv2.COLOR_BGR2GRAY)
            if tmpl_gray.shape != crop_gray.shape:
                tmpl_gray = cv2.resize(tmpl_gray, (crop_gray.shape[1], crop_gray.shape[0]))
            res = cv2.matchTemplate(crop_gray, tmpl_gray, cv2.TM_CCOEFF_NORMED)
            score = float(res[0][0])
            prev = scores.get(card_id)
            if prev is None or score > prev:
                scores[card_id] = score
        if not scores:
            continue
        top = sorted(scores.items(), key=lambda item: item[1], reverse=True)[:topk]
        results[idx] = top
    return results


