def _get_hand_slot_centers(iar: numpy.ndarray) -> tuple[list[tuple[int, int]], int, int, int]:
    h, w = iar.shape[:2]
    # Use fixed anchors scaled from the reference resolution (more stable than edge detection).
    base_w, base_h = 419.0, 633.0
    sx = w / base_w
    sy = h / base_h
    try:
        centers = [
            (int((x + TOTAL_WIDTH / 2) * sx), int((y + TOTAL_HEIGHT / 2) * sy))
            for x, y in toplefts
        ]
        slot_w = max(1, int(TOTAL_WIDTH * sx))
        biases: list[float]
        if HAND_SLOT_X_BIAS_SLOTS:
            try:
                parts = [float(p.strip()) for p in HAND_SLOT_X_BIAS_SLOTS.split(",") if p.strip()]
                biases = parts if len(parts) == 4 else [HAND_SLOT_X_BIAS] * 4
            except Exception:
                biases = [HAND_SLOT_X_BIAS] * 4
        else:
            biases = HAND_SLOT_X_BIAS_DEFAULTS
        centers = [
            (min(w - 1, max(0, cx + int(slot_w * biases[idx]))), cy)
            for idx, (cx, cy) in enumerate(centers)
        ]
        y_vals = [int(y * sy) for _, y in toplefts]
        y_min = max(0, min(y_vals))
        y_max = min(h - 1, max(y_vals) + int(TOTAL_HEIGHT * sy))
        return centers, slot_w, y_min, y_max
    except Exception:
        pass

    x_min, x_max = int(w * 0.10), int(w * 0.90)
    y_min, y_max = int(h * 0.78), int(h * 0.96)

    # Try to locate the hand row using edge density (more robust to DPI/res changes).
    try:
        roi = iar[y_min:y_max, x_min:x_max]
        gray = cv2.cvtColor(roi, cv2.COLOR_BGR2GRAY)
        edges_y = cv2.Sobel(gray, cv2.CV_32F, 0, 1, ksize=3)
        row_score = numpy.mean(numpy.abs(edges_y), axis=1)
        if row_score.size > 0 and row_score.max() > 5.0:
            y_center = y_min + int(numpy.argmax(row_score))
        else:
            y_center = (y_min + y_max) // 2

        edges_x = cv2.Sobel(gray, cv2.CV_32F, 1, 0, ksize=3)
        col_score = numpy.mean(numpy.abs(edges_x), axis=0)
        if col_score.size > 0 and col_score.max() > 5.0:
            thresh = col_score.max() * 0.25
            cols = numpy.where(col_score >= thresh)[0]
            if cols.size > 0:
                x_min = x_min + int(cols.min())
                x_max = x_min + int(cols.max() - cols.min())
    except Exception:
        y_center = (y_min + y_max) // 2

    # Bias downward to center on the card art (avoid cropping just the top edge).
    try:
        y_bias = int((y_max - y_min) * 0.18)
        y_center = min(y_max - 5, max(y_min + 5, y_center + y_bias))
    except Exception:
        pass

    slot_w = max((x_max - x_min) // 4, 1)
    centers = [((x_min + slot_w * i) + slot_w // 2, y_center) for i in range(4)]
    return centers, slot_w, y_min, y_max


def _get_hand_crop_size(iar: numpy.ndarray) -> tuple[int, int]:
    h, w = iar.shape[:2]
    scale = min(w / 450.0, h / 800.0)
    width = int(HAND_CROP_WIDTH * scale)
    height = int(HAND_CROP_HEIGHT * scale)
    width = max(80, min(160, width))
    height = max(80, min(160, height))
    return width, height


def _pad_to_size(image, target_height, target_width):
    height, width = image.shape[:2]
    if height == target_height and width == target_width:
        return image

    pad_bottom = max(target_height - height, 0)
    pad_right = max(target_width - width, 0)
    if pad_bottom == 0 and pad_right == 0:
        return image[:target_height, :target_width]

    return numpy.pad(
        image,
        ((0, pad_bottom), (0, pad_right), (0, 0)),
        mode="edge",
    )[:target_height, :target_width]


def get_hand_card_crop(emulator, card_index):
    iar = _get_battle_iar(emulator)
    centers, slot_w, y_min, y_max = _get_hand_slot_centers(iar)
    base_w, base_h = _get_hand_crop_size(iar)
    width = min(base_w, int(slot_w * 0.9))
    height = min(base_h, int(slot_w * 1.05))
    width = max(60, width)
    height = max(60, height)
    cx, cy = centers[card_index]

    x1 = max(0, int(cx - width // 2))
    y1 = max(0, int(cy - height // 2))
    x2 = min(iar.shape[1], x1 + width)
    y2 = min(iar.shape[0], y1 + height)

    crop = iar[y1:y2, x1:x2]
    return _pad_to_size(crop, base_h, base_w)


def get_hand_card_predictions(emulator, topk: int = 3) -> dict[int, list[tuple[str, float]]]:
    classifier = _get_hand_classifier()
    if classifier is None:
        return {}
    results: dict[int, list[tuple[str, float]]] = {}
    for idx in range(4):
        crop = get_hand_card_crop(emulator, idx)
        try:
            preds = classifier.predict_topk(crop, k=topk)
            normalized = [(_normalize_card_name(name), conf) for name, conf in preds]
            if ACTIVE_DECK_FILTER is not None:
                deck_only = [(name, conf) for name, conf in normalized if name in ACTIVE_DECK_FILTER]
                results[idx] = deck_only if deck_only else normalized
            else:
                results[idx] = normalized
        except Exception:
            continue
    return results


def check_which_cards_are_available(emulator, check_champion=False, check_side=False):
    global battle_iar
    battle_iar = emulator.screenshot()
    card_exists_list = []

    if check_champion and (
        check_for_champion_ability(
            battle_iar[462][324],
            battle_iar[453][334],
            battle_iar[462][336],
        )
    ):
        emulator.click(330, 460)

    if check_side:
        global play_side
        _, play_side = switch_side()

    def _has_purple_cost(crop: numpy.ndarray) -> bool:
        if crop is None or crop.size == 0:
            return False
        hsv = cv2.cvtColor(crop, cv2.COLOR_BGR2HSV)
        lower = numpy.array([135, 60, 60])
        upper = numpy.array([175, 255, 255])
        mask = cv2.inRange(hsv, lower, upper)
        return (mask > 0).mean() > 0.005

    def _is_available(crop: numpy.ndarray) -> bool:
        if _has_purple_cost(crop):
            return True
        hsv = cv2.cvtColor(crop, cv2.COLOR_BGR2HSV)
        return numpy.median(hsv[:, :, 1]) > 35 and numpy.median(hsv[:, :, 2]) > 50

    for i in range(4):
        crop = get_hand_card_crop(emulator, i)
        if crop is None:
            continue
        if _is_available(crop):
            card_exists_list.append(i)

    return card_exists_list


def check_for_champion_ability(a, b, c):
    pixels = numpy.array([a, b, c])
    colors = numpy.array(
        [
            [215, 28, 223],
            [240, 39, 254],
            [239, 40, 251],
        ],
    )

    for p in pixels:
        if numpy.any(numpy.all(numpy.abs(colors - p) <= 30, axis=1)):
            return True

    return False


def _update_hand_stable(card_index: int, card_id: str, conf: float, now_ts: float) -> None:
    streak = _HAND_STREAK.get(card_index, {})
    last_id = streak.get("card_id")
    count = streak.get("count", 0) if last_id == card_id else 0
    count = int(min(5, count + 1))
    _HAND_STREAK[card_index] = {"card_id": card_id, "count": count, "ts": now_ts}
    if conf >= HAND_STABLE_MIN_CONF or count >= 2:
        _HAND_STABLE[card_index] = {"card_id": card_id, "ts": now_ts}


def _get_hand_stable(card_index: int, now_ts: float) -> str | None:
    entry = _HAND_STABLE.get(card_index)
    if not entry:
        return None
    ts = float(entry.get("ts", 0.0))
    if now_ts - ts > HAND_STABLE_TTL:
        return None
    return str(entry.get("card_id"))


def identify_hand_cards(emulator, card_index):
    now_ts = time.time()
    stable = _get_hand_stable(card_index, now_ts)
    tmpl_id, tmpl_score = match_card_template(emulator, card_index, return_score=True)
    if tmpl_id is not None and tmpl_score >= HAND_TEMPLATE_THRESHOLD:
        _update_hand_stable(card_index, tmpl_id, tmpl_score, now_ts)
        return tmpl_id
    if tmpl_id is not None and stable == tmpl_id and tmpl_score >= (HAND_TEMPLATE_THRESHOLD - 0.04):
        _update_hand_stable(card_index, tmpl_id, tmpl_score, now_ts)
        return tmpl_id
    if ACTIVE_DECK_FILTER is not None and tmpl_id is not None and tmpl_score >= HAND_TEMPLATE_FALLBACK:
        _update_hand_stable(card_index, tmpl_id, tmpl_score, now_ts)
        return tmpl_id

    classifier = _get_hand_classifier()
    if classifier is not None and HAND_USE_CLASSIFIER:
        crop = get_hand_card_crop(emulator, card_index)
        try:
            preds = classifier.predict_topk(crop, k=5)
        except Exception:
            preds = None
        if preds:
            preds = [(_normalize_card_name(name), float(conf)) for name, conf in preds]
            top1_name, top1_conf = preds[0]
            top2_conf = preds[1][1] if len(preds) > 1 else 0.0
            gap = top1_conf - top2_conf
            if ACTIVE_DECK_FILTER is not None:
                deck_preds = [(name, conf) for name, conf in preds if name in ACTIVE_DECK_FILTER]
                if deck_preds:
                    top1_name, top1_conf = deck_preds[0]
                    top2_conf = deck_preds[1][1] if len(deck_preds) > 1 else 0.0
                    gap = top1_conf - top2_conf
                if top1_name in ACTIVE_DECK_FILTER and (
                    top1_conf >= HAND_CLASSIFIER_MIN_CONF_DECK
                    or (top1_conf >= HAND_STABLE_MIN_CONF and gap >= HAND_STABLE_MIN_GAP)
                ):
                    _update_hand_stable(card_index, top1_name, top1_conf, now_ts)
                    return top1_name
                # If the classifier is confidently predicting a non-deck card, ignore it.
                if top1_conf >= 0.6 and top1_name not in ACTIVE_DECK_FILTER:
                    preds = None
                # If classifier is shaky, use last stable reading.
                if stable is not None and top1_conf >= HAND_STABLE_MIN_CONF:
                    return stable
            else:
                if top1_conf >= HAND_CLASSIFIER_MIN_CONF:
                    _update_hand_stable(card_index, top1_name, top1_conf, now_ts)
                    return top1_name
    if stable is not None:
        return stable
    # Fall back to templates/pixel matching if classifier confidence is low.
    color_chosen_card = get_all_pixel_data(emulator, card_index)
    return find_closest_card(color_chosen_card)


