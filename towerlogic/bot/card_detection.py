def _load_card_templates() -> list[tuple[str, numpy.ndarray]]:
    global _CARD_TEMPLATES
    deck_key = ",".join(sorted(ACTIVE_DECK_FILTER)) if ACTIVE_DECK_FILTER else "__all__"
    if _CARD_TEMPLATES is not None and _CARD_TEMPLATE_SOURCE == deck_key:
        return _CARD_TEMPLATES
    templates: list[tuple[str, numpy.ndarray]] = []
    per_card_counts: dict[str, int] = {}
    slot_map = {
        "unknown_slot2": "mini_pekka",
        "unknown_slot3": "giant",
    }
    classifier = _get_hand_classifier()
    for base in CARD_TEMPLATE_DIRS:
        if not os.path.isdir(base):
            continue
        for name in os.listdir(base):
            if not name.lower().endswith((".png", ".jpg", ".jpeg")):
                continue
            card_id = os.path.splitext(name)[0]
            for prefix, mapped in slot_map.items():
                if name.startswith(prefix):
                    card_id = mapped
                    break
            path = os.path.join(base, name)
            img = cv2.imread(path, cv2.IMREAD_COLOR)
            if img is None:
                continue
            norm_id = _normalize_card_name(card_id)
            # Allow multiple templates per card using suffixes like _1, _2, etc.
            norm_id = re.sub(r"_\d+$", "", norm_id)
            if ACTIVE_DECK_FILTER is not None and norm_id not in ACTIVE_DECK_FILTER:
                # Try to auto-label unknown images using the classifier when enabled.
                if classifier is not None and HAND_USE_CLASSIFIER:
                    try:
                        pred_name, conf = classifier.predict(img)
                    except Exception:
                        pred_name, conf = None, None
                    if pred_name is not None and conf is not None:
                        pred_name = _normalize_card_name(pred_name)
                        if pred_name in ACTIVE_DECK_FILTER and conf >= 0.85:
                            norm_id = pred_name
                        else:
                            continue
                else:
                    continue
            count = per_card_counts.get(norm_id, 0)
            if count >= 6:
                continue
            per_card_counts[norm_id] = count + 1
            templates.append((norm_id, img))
    # Also load from dataset folders (cards/train|valid|test) if present.
    max_per_card = 4
    for base in _dataset_dirs():
        if not os.path.isdir(base):
            continue
        for name in os.listdir(base):
            class_dir = os.path.join(base, name)
            if not os.path.isdir(class_dir):
                continue
            card_id = _normalize_card_name(name)
            if ACTIVE_DECK_FILTER is not None and card_id not in ACTIVE_DECK_FILTER:
                continue
            img_files = [
                f for f in os.listdir(class_dir) if f.lower().endswith((".png", ".jpg", ".jpeg"))
            ]
            img_files.sort()
            for img_name in img_files[:max_per_card]:
                path = os.path.join(class_dir, img_name)
                img = cv2.imread(path, cv2.IMREAD_COLOR)
                if img is None:
                    continue
                count = per_card_counts.get(card_id, 0)
                if count >= 10:
                    break
                per_card_counts[card_id] = count + 1
                templates.append((card_id, img))
    _CARD_TEMPLATES = templates
    globals()["_CARD_TEMPLATE_SOURCE"] = deck_key
    return templates


